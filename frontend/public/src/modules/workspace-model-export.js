// 3D 모델 생성기로 넘길 데이터와 SketchUp Ruby 스크립트 생성.

import {
  getPhotosForSpace,
  isWholeHomeSpaceId,
  modelRooms,
  wholeHomeRoom,
  WHOLE_HOME_SPACE_ID,
} from "./workspace-selectors.js";
import { uniquePhotos } from "./workspace-views-photos.js";

// SketchUp 브리지 — 로컬에서 떠 있는 SketchUp 플러그인이 수신하는 endpoint.
// 가족 다른 PC 에서 포트가 다를 경우를 대비해 한 곳에 묶음.
// 기본값은 SketchUp Ruby Bridge 의 관용 포트.
const SKETCHUP_BRIDGE_ENDPOINT = "http://127.0.0.1:43434/command";

/** @typedef {import("./workspace.js").WorkspaceState} WorkspaceState */
/** @typedef {import("../api.js").LineItem} LineItem */
/** @typedef {import("../api.js").Space} Space */

/** @param {WorkspaceState} s */
export function buildModelPayload(s) {
  const rooms = modelRooms(s);
  return {
    project: {
      id: s.bundle.project.id,
      name: s.bundle.project.name,
      address: s.bundle.project.address,
      sizeKr: s.bundle.project.sizeKr,
    },
    source: {
      floorplans: floorplanAttachments(s).map((file) => ({
        id: file.id,
        filename: file.filename,
        url: portableAttachmentUrl(file.blobUrl),
      })),
      photoCount: modelPhotos(s, rooms, wholeHomeRoom(s)).length,
    },
    rooms: rooms.map((room, index) => ({
      id: room.id,
      name: room.name,
      areaSqm: room.areaSqm,
      geometry: roomGeometry(room, index),
      lineItems: relatedLineItems(s, [room]).map((item) => ({
        id: item.id,
        label: item.label,
        workItemLabel: item.workItemLabel,
      })),
    })),
  };
}

/** @param {WorkspaceState} s */
export function buildSketchUpRubyScript(s) {
  const payload = buildModelPayload(s);
  const rooms = payload.rooms;
  const roomData = rooms.map((room) => `  {
    name: ${rubyString(room.name)},
    x_m: ${rubyNumber(room.geometry.xM)},
    y_m: ${rubyNumber(room.geometry.yM)},
    width_m: ${rubyNumber(room.geometry.widthM)},
    depth_m: ${rubyNumber(room.geometry.depthM)},
    height_m: 2.4,
    area_sqm: ${rubyNumber(room.areaSqm ?? 0)},
    line_items: [${room.lineItems.map((item) => rubyString(item.label)).join(", ")}]
  }`).join(",\n");

  return `# Generated by 인테리어 견적 관리 v2
# Project: ${payload.project.name}
# Paste into SketchUp Ruby Console or run through a SketchUp MCP bridge.

model = Sketchup.active_model
model.start_operation(${rubyString(`Generate ${payload.project.name} model`)}, true)

entities = model.active_entities
materials = model.materials
floor_mat = materials.add("Generated floor")
floor_mat.color = Sketchup::Color.new(220, 234, 254)
wall_mat = materials.add("Generated wall")
wall_mat.color = Sketchup::Color.new(148, 163, 184)

ROOMS = [
${roomData}
]

def add_box(entities, x_m, y_m, width_m, depth_m, height_m, material)
  pts = [
    [x_m.m, y_m.m, 0],
    [(x_m + width_m).m, y_m.m, 0],
    [(x_m + width_m).m, (y_m + depth_m).m, 0],
    [x_m.m, (y_m + depth_m).m, 0]
  ]
  face = entities.add_face(pts)
  face.material = material
  face.pushpull(height_m.m)
  face
end

def add_room_label(entities, room)
  point = Geom::Point3d.new((room[:x_m] + 0.2).m, (room[:y_m] + 0.2).m, 2.55.m)
  entities.add_text(room[:name], point)
end

ROOMS.each do |room|
  group = entities.add_group
  room_entities = group.entities
  floor = add_box(room_entities, room[:x_m], room[:y_m], room[:width_m], room[:depth_m], 0.04, floor_mat)
  wall_t = 0.12
  add_box(room_entities, room[:x_m], room[:y_m], room[:width_m], wall_t, room[:height_m], wall_mat)
  add_box(room_entities, room[:x_m], room[:y_m] + room[:depth_m] - wall_t, room[:width_m], wall_t, room[:height_m], wall_mat)
  add_box(room_entities, room[:x_m], room[:y_m], wall_t, room[:depth_m], room[:height_m], wall_mat)
  add_box(room_entities, room[:x_m] + room[:width_m] - wall_t, room[:y_m], wall_t, room[:depth_m], room[:height_m], wall_mat)
  group.name = room[:name]
  add_room_label(room_entities, room)
end

model.commit_operation
model.active_view.zoom_extents
`;
}

/** @param {WorkspaceState} s */
export function buildSketchUpBridgeCommand(s) {
  return {
    endpoint: SKETCHUP_BRIDGE_ENDPOINT,
    method: "POST",
    body: {
      command: "generate_model",
      payload: buildModelPayload(s),
    },
  };
}

/** @param {WorkspaceState} s @param {Space[]} rooms @param {Space|null} selected */
function modelPhotos(s, rooms, selected) {
  const sources = selected && isWholeHomeSpaceId(selected.id) ? [selected, ...rooms] : rooms;
  return uniquePhotos(sources.flatMap((room) => getPhotosForSpace(s, room.id)));
}

/** @param {WorkspaceState} s @param {Space[]} rooms */
function relatedLineItems(s, rooms) {
  if (rooms.some((room) => room.id === WHOLE_HOME_SPACE_ID)) return s.bundle.lineItems;
  const roomIds = new Set(rooms.map((room) => room.id));
  return s.bundle.lineItems.filter((item) => item.spaceId && roomIds.has(item.spaceId));
}

/** @param {WorkspaceState} s */
function floorplanAttachments(s) {
  return (s.bundle.attachments ?? []).filter((attachment) =>
    attachment.kind === "drawing" || attachment.photoKind === "floorplan" || attachment.photoKind === "naver_floorplan");
}

/** @param {string} url */
function portableAttachmentUrl(url) {
  return url.startsWith("data:") ? "[inline data url omitted]" : url;
}

/** @param {Space} room @param {number} index */
function roomGeometry(room, index) {
  const area = safeArea(room) || 9;
  const widthM = Number(Math.max(1.8, Math.sqrt(area * 1.22)).toFixed(2));
  const depthM = Number(Math.max(1.8, area / widthM).toFixed(2));
  const col = index % 4;
  const row = Math.floor(index / 4);
  return {
    xM: Number((col * 5.2).toFixed(2)),
    yM: Number((row * 4.6 + (col % 2) * 0.8).toFixed(2)),
    widthM,
    depthM,
  };
}

/** @param {Space} room */
function safeArea(room) {
  return typeof room.areaSqm === "number" && Number.isFinite(room.areaSqm) ? room.areaSqm : 0;
}

/** @param {string} value */
function rubyString(value) {
  return JSON.stringify(value);
}

/** @param {number} value */
function rubyNumber(value) {
  return Number.isFinite(value) ? String(Number(value.toFixed(3))) : "0";
}
